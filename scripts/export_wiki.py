"""Build a reviewable GitHub Wiki checkout from committed documentation, without publishing."""

import argparse
import hashlib
import json
import os
import re
import subprocess
from collections import Counter
from pathlib import Path
from urllib.parse import quote, urlsplit

if __package__:
    from .wiki_export.markdown import rewrite
else:
    from wiki_export.markdown import rewrite

SOURCE_URL = "https://github.com/Gam1409/taleweaver"
MANIFEST = ".taleweaver-wiki-export.json"
MARKER = "<!-- Generated by scripts/export_wiki.py; edit repository sources. -->\n"
MAX_FILE_BYTES = 2 * 1024 * 1024
MAX_TOTAL_BYTES = 32 * 1024 * 1024
MAX_PAGES = 512
IMMUTABLE = "docs/research/chpm/CHPM_Research_Architecture_v0_2_RU.md"
ALIASES = {
    "docs/README.md": "Home",
    "README.md": "Project",
    "ASSETS.md": "Assets",
    "AGENTS.md": "Contributor-Instructions",
    ".github/copilot-instructions.md": "Copilot-Instructions",
}
SECTIONS = (
    ("Start here", "start-here"),
    ("Players and sessions", "players-and-sessions"),
    ("NPC memory and world", "npc-memory-and-world"),
    ("Images and workflows", "images-and-workflows"),
    ("Authoring and formats", "authoring-and-formats"),
    ("Installation and providers", "installation-and-providers"),
    ("Engineering", "engineering"),
)


def _git(repo: Path, *args: str) -> bytes:
    result = subprocess.run(
        ["git", "--no-replace-objects", "--no-pager", "-C", str(repo), *args],
        capture_output=True,
        check=False,
        env={**os.environ, "GIT_NO_LAZY_FETCH": "1"},
    )
    if result.returncode:
        raise ValueError("Cannot read the requested Git revision.")
    return result.stdout


def _snapshot(repo: Path, revision: str) -> tuple[str, dict[str, tuple[str, int, str]]]:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/-]{0,199}", revision) or ".." in revision:
        raise ValueError("Invalid source revision; use a ref name or commit SHA.")
    sha = (
        _git(repo, "rev-parse", "--verify", "--end-of-options", revision + "^{commit}")
        .decode()
        .strip()
    )
    if not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", sha):
        raise ValueError("Invalid resolved source revision.")
    entries = {}
    for record in _git(repo, "ls-tree", "-rzl", "--full-tree", sha).split(b"\0"):
        if not record:
            continue
        metadata, name = record.split(b"\t", 1)
        mode, kind, blob, size = metadata.decode().split()
        if kind == "blob":
            entries[name.decode("utf-8")] = (blob, int(size), mode)
    return sha, entries


def _source_url(value: str) -> str:
    parsed = urlsplit(value.rstrip("/"))
    if (
        parsed.scheme != "https"
        or parsed.netloc != "github.com"
        or parsed.query
        or parsed.fragment
        or not re.fullmatch(r"/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", parsed.path)
    ):
        raise ValueError("The source URL must be a credential-free HTTPS GitHub repository URL.")
    return value.rstrip("/")


def _slug(path: str) -> str:
    parts = path.removesuffix(".md").removesuffix(".mermaid").split("/")
    if parts[0] == "docs":
        parts.pop(0)
    if parts[-1].lower() == "readme":
        parts.pop()
    return (
        "--".join(re.sub(r"[^\w.-]+", "-", p.replace("_", "-")).strip("-.").lower() for p in parts)
        or "document"
    )


def _page_names(paths: list[str]) -> dict[str, str]:
    candidates = {p: ALIASES.get(p, _slug(p)) for p in paths}
    counts = Counter(name.casefold() for name in candidates.values())
    reserved = {value.casefold() for value in ALIASES.values()} | {"_sidebar", "_footer"}
    result = {}
    for path, candidate in candidates.items():
        collision = path not in ALIASES and (
            counts[candidate.casefold()] > 1 or candidate.casefold() in reserved
        )
        result[path] = (
            candidate + "--" + hashlib.sha256(path.encode()).hexdigest()[:8]
            if collision
            else candidate
        )
    if len(set(name.casefold() for name in result.values())) != len(result):
        raise ValueError("Wiki page name collision; choose distinct source paths.")
    return result


def _render(repo: Path, sha: str, tree: dict, source: str) -> tuple[dict[str, str], dict[str, str]]:
    paths = sorted(
        p
        for p, entry in tree.items()
        if p.endswith((".md", ".mermaid"))
        and "/licenses/" not in p
        and not Path(p).name.lower().startswith("license")
        and p != IMMUTABLE
        and entry[2] != "120000"
    )
    if len(paths) > MAX_PAGES or sum(tree[p][1] for p in paths) > MAX_TOTAL_BYTES:
        raise ValueError("Documentation size exceeds the Wiki export limit.")
    if any(tree[p][1] > MAX_FILE_BYTES for p in paths):
        raise ValueError("A documentation file exceeds the text size limit.")
    pages = _page_names(paths)
    files, total = {}, 0
    for path in paths:
        text = _git(repo, "cat-file", "blob", tree[path][0]).decode("utf-8")
        body = (
            f"# {Path(path).stem}\n\n```mermaid\n{text.rstrip()}\n```\n"
            if path.endswith(".mermaid")
            else rewrite(text, path, pages, tree, source, sha)
        )
        page = MARKER + body
        total += len(page.encode())
        if len(page.encode()) > MAX_FILE_BYTES or total > MAX_TOTAL_BYTES:
            raise ValueError("Generated documentation size exceeds the Wiki export limit.")
        files[pages[path] + ".md"] = page
    if "Home.md" not in files:
        current, history = [], []
        for path, name in pages.items():
            target = (
                history
                if re.search(r"research|history|audit|review|design|RELEASE", path)
                else current
            )
            target.append(f"- [{name}]({quote(name)})")
        files["Home.md"] = (
            MARKER
            + "# Documentation\n\n## Current guides\n\n"
            + "\n".join(current)
            + "\n\n## Research and history\n\n"
            + "\n".join(history)
            + "\n"
        )
    home = files["Home.md"].lower()
    anchors = {
        re.sub(r"[^\w\s-]", "", line.lstrip("#").strip()).replace(" ", "-")
        for line in home.splitlines()
        if line.startswith("#")
    }
    sections = [f"- [{label}](Home#{anchor})" for label, anchor in SECTIONS if anchor in anchors]
    if not sections:
        sections = ["- [Documentation index](Home)"]
    history = (
        ["- [Research and history](Home#research-and-history)"]
        if "research-and-history" in anchors
        else [
            f"- [{name}]({quote(name)})"
            for path, name in pages.items()
            if re.search(r"research|history|audit|review|design|RELEASE", path)
        ][:8]
    )
    overview = "[Home](Home)" + (" · [Project](Project)" if "Project.md" in files else "")
    files["_Sidebar.md"] = (
        MARKER
        + "## Documentation\n\n"
        + overview
        + "\n\n### Current guides and references\n\n"
        + "\n".join(sections)
        + "\n\n### Research and history\n\n"
        + "\n".join(history)
        + "\n"
    )
    files["_Footer.md"] = (
        MARKER
        + f"Source of truth: [repository documentation]({source}/tree/{sha}/docs) · [revision `{sha}`]({source}/commit/{sha}). Edit the repository, then regenerate this Wiki.\n"
    )
    if any(len(text.encode()) > MAX_FILE_BYTES for text in files.values()):
        raise ValueError("A generated page exceeds the text size limit.")
    return pages, files


def _existing(output: Path) -> dict[str, str]:
    manifest = output / MANIFEST
    if manifest.is_symlink():
        raise ValueError("Refusing a symlink export manifest.")
    if not manifest.exists():
        return {}
    if not manifest.is_file():
        raise ValueError("Invalid export manifest type.")
    if manifest.stat().st_size > MAX_FILE_BYTES:
        raise ValueError("Export manifest size exceeds its limit.")
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
        files = data["files"]
        if (
            type(data["version"]) is not int
            or data["version"] != 1
            or not isinstance(files, dict)
            or len(files) > MAX_PAGES + 3
        ):
            raise ValueError("Invalid export manifest.")
        valid = all(
            isinstance(name, str)
            and Path(name).name == name
            and name.endswith(".md")
            and "\\" not in name
            and isinstance(value, str)
            and re.fullmatch(r"[0-9a-f]{64}", value)
            for name, value in files.items()
        )
        if not valid:
            raise ValueError("Invalid export manifest filenames or hashes.")
        return files
    except (KeyError, TypeError, json.JSONDecodeError) as exc:
        raise ValueError("Invalid export manifest.") from exc


def _validate_output(output: Path, previous: dict[str, str], files: dict[str, str]) -> None:
    managed = previous.keys() | files.keys()
    folded = {name.casefold() for name in managed}
    conflicts = (
        [
            path.name
            for path in output.iterdir()
            if path.name.casefold() in folded and path.name not in managed
        ]
        if output.is_dir()
        else []
    )
    if conflicts:
        raise ValueError("Refusing unmanaged pages whose names differ only by case.")
    for name in managed:
        path = output / name
        if path.is_symlink():
            raise ValueError(f"Refusing symlink output page: {name}")
        if not path.exists():
            continue
        if name not in previous:
            raise ValueError(f"Refusing to overwrite unmanaged Wiki page: {name}")
        if not path.is_file() or path.stat().st_size > MAX_FILE_BYTES:
            raise ValueError(f"Invalid existing page size or type: {name}")
        payload = path.read_bytes()
        if (
            not payload.startswith(MARKER.encode())
            or hashlib.sha256(payload).hexdigest() != previous[name]
        ):
            raise ValueError(f"Previously generated page was modified: {name}")


def export(
    repo: Path,
    output: Path,
    *,
    revision: str = "HEAD",
    source_url: str = SOURCE_URL,
    dry_run: bool = False,
) -> dict:
    """Generate only local files after validating every replacement and cleanup target."""
    repo, output = Path(repo).resolve(), Path(output).resolve()
    if output == repo or repo in output.parents:
        raise ValueError("Wiki output must be outside the source checkout.")
    source_url = _source_url(source_url)
    sha, tree = _snapshot(repo, revision)
    pages, files = _render(repo, sha, tree, source_url)
    previous = _existing(output)
    _validate_output(output, previous, files)
    result = {"revision": sha, "pages": pages}
    if dry_run:
        return result
    output.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (output / name).write_text(text, encoding="utf-8", newline="")
    for name in previous.keys() - files.keys():
        (output / name).unlink(missing_ok=True)
    manifest = {
        "version": 1,
        "revision": sha,
        "source": source_url,
        "pages": pages,
        "files": {name: hashlib.sha256(text.encode()).hexdigest() for name, text in files.items()},
    }
    (output / MANIFEST).write_text(
        json.dumps(manifest, ensure_ascii=False, sort_keys=True, indent=2) + "\n",
        encoding="utf-8",
        newline="",
    )
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--revision", default="HEAD")
    parser.add_argument("--source-url", default=SOURCE_URL)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    try:
        result = export(
            args.repo,
            args.output,
            revision=args.revision,
            source_url=args.source_url,
            dry_run=args.dry_run,
        )
    except (ValueError, OSError, UnicodeError) as exc:
        parser.error(str(exc))
    print(
        json.dumps(
            {
                "revision": result["revision"],
                "page_count": len(result["pages"]),
                "dry_run": args.dry_run,
            },
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
