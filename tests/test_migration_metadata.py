"""Autogeneration must preserve recovery archives and existing uniqueness constraints."""

import pytest
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text

from alembic import command
from backend.core.config import settings


def test_fresh_upgrade_has_no_model_drift_and_preserves_the_repair_archive(tmp_path, monkeypatch):
    path = tmp_path / "schema.sqlite"
    monkeypatch.setattr(settings, "DATABASE_URL", "sqlite:///" + str(path))
    config = Config("alembic.ini")
    config.attributes["configure_logger"] = False
    command.upgrade(config, "head")
    engine = create_engine(settings.DATABASE_URL)
    try:
        with engine.begin() as connection:
            connection.execute(
                text(
                    "INSERT INTO referential_repair_archive "
                    "(source_table, source_rowid, payload, reason) VALUES ('old_table', 7, :payload, 'test recovery')"
                ),
                {"payload": '{"id":"keep-original-evidence"}'},
            )
        command.check(config)
        with engine.connect() as connection:
            assert (
                connection.scalar(
                    text("SELECT payload FROM referential_repair_archive WHERE source_rowid = 7")
                )
                == '{"id":"keep-original-evidence"}'
            )
            unique = inspect(connection).get_unique_constraints("ai_fix_cache")
            assert any(
                set(row["column_names"]) == {"template_id", "user_id", "finding_signature"}
                for row in unique
            )
        with engine.begin() as connection:
            connection.execute(text("CREATE TABLE untracked_control (id INTEGER PRIMARY KEY)"))
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(config)
    finally:
        engine.dispose()
