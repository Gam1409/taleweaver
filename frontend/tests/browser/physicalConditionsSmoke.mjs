import assert from 'node:assert/strict'
import process from 'node:process'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1360, height: 960 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/api/**', route => route.fulfill({ json: {} }))
try {
  await page.goto((process.env.FRONTEND_URL || 'http://127.0.0.1:5199') + '/tests/browser/physicalConditions.html')
  await page.getByRole('button', { name: 'State', exact: true }).click()
  await page.getByText('A bandaged neck wound.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  assert.equal(await page.getByLabel('Body part or item area', { exact: true }).isDisabled(), true)
  await page.getByLabel('Operation', { exact: true }).selectOption('heal')
  await page.getByRole('button', { name: 'Save condition', exact: true }).click()
  const first = JSON.parse((await page.locator('#last-command').textContent()).slice('/debug condition '.length))
  assert.equal(first.condition_id, 'C1')
  assert.equal(first.operation, 'heal')
  assert.equal(first.expected_revision, 1)
  assert.equal(first.target_id, undefined)
  assert.equal(await page.getByRole('button', { name: 'Save condition', exact: true }).isDisabled(), true)
  await page.getByLabel('Show resolved', { exact: true }).check()
  await page.getByText('injury · resolved · public', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Record condition', exact: true }).click()
  await page.getByLabel('Subject', { exact: true }).selectOption('RIN')
  await page.getByLabel('Kind', { exact: true }).selectOption('contamination')
  await page.getByLabel('Body part or item area', { exact: true }).fill('hands')
  await page.getByLabel('Current detail', { exact: true }).fill('<script>Mud on both hands.</script>')
  await page.getByRole('button', { name: 'Save condition', exact: true }).click()
  const second = JSON.parse((await page.locator('#last-command').textContent()).slice('/debug condition '.length))
  assert.equal(second.operation, 'record')
  assert.equal(second.visibility, 'private')
  assert.equal(second.expected_revision, 2)
  await page.getByText('<script>Mud on both hands.</script>', { exact: true }).waitFor()
  assert.equal(await page.locator('article script').count(), 0)
  await page.screenshot({ path: '/tmp/physical-conditions-debug-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.locator('body').evaluate(element => element.scrollWidth <= window.innerWidth), true)
  await page.getByRole('button', { name: 'Save condition', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/physical-conditions-debug-mobile.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('Physical condition debug browser checks passed.')
} finally { await browser.close() }
