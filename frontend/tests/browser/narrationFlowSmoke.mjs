import assert from 'node:assert/strict'
import process from 'node:process'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto((process.env.FRONTEND_URL || 'http://127.0.0.1:5214') + '/tests/browser/narrationFlow.html')
  const session = page.getByRole('region', { name: 'Session narration', exact: true })
  const defaults = page.getByRole('region', { name: 'Adventure narrator defaults', exact: true })
  const flow = session.getByLabel('Narration flow', { exact: true })
  const authorFlow = defaults.getByLabel('Narration flow', { exact: true })
  await page.waitForFunction(() => { const nodes = [...document.querySelectorAll('[aria-label="Narration flow"]')]; return nodes.length === 2 && nodes.every(node => !node.disabled) })
  assert.equal(await flow.inputValue(), 'gentle')
  assert.equal(await authorFlow.inputValue(), 'gentle')
  assert.equal(await defaults.getByRole('button', { name: 'Save narrator defaults', exact: true }).isDisabled(), true)
  assert.notEqual(await flow.getAttribute('aria-describedby'), await authorFlow.getAttribute('aria-describedby'))
  await flow.focus()
  await page.keyboard.press('Home')
  assert.equal(await flow.inputValue(), 'off')
  await page.keyboard.press('End')
  assert.equal(await flow.inputValue(), 'balanced')
  await session.getByLabel('Literary voice', { exact: true }).selectOption('clear_voice')
  await session.getByLabel('Amount of narration', { exact: true }).selectOption('rich')
  await flow.selectOption('off')
  assert.equal(await page.evaluate(() => window.narrationFlowFixture.writes.length), 0)
  await page.evaluate(() => window.narrationFlowFixture.failNextSave())
  await session.getByRole('button', { name: 'Save session', exact: true }).click()
  await session.getByText('Session save failed.', { exact: true }).waitFor()
  assert.equal(await flow.inputValue(), 'off')
  await session.getByRole('alert').waitFor()
  await session.getByRole('button', { name: 'Save session', exact: true }).click()
  await session.getByText('Session preferences saved.', { exact: true }).waitFor()
  const saved = await page.evaluate(() => window.narrationFlowFixture.writes.at(-1))
  assert.equal(saved.path, '/adventures/session-one/narrator-settings')
  assert.equal(saved.body.flow, 'off')
  assert.equal(saved.body.voice.id, 'clear_voice')
  assert.equal(saved.body.verbosity, 'rich')
  await session.getByRole('button', { name: 'Switch session', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[aria-label="Session narration"] [aria-label="Narration flow"]').value === 'gentle')
  await session.getByRole('button', { name: 'Switch session', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[aria-label="Session narration"] [aria-label="Narration flow"]').value === 'off')
  assert.equal(await session.getByLabel('Literary voice', { exact: true }).inputValue(), 'clear_voice')
  assert.equal(await session.getByLabel('Amount of narration', { exact: true }).inputValue(), 'rich')
  await authorFlow.selectOption('balanced')
  await defaults.getByRole('button', { name: 'Save narrator defaults', exact: true }).click()
  await page.waitForFunction(() => window.narrationFlowFixture.writes.some(write => write.path.endsWith('/narrator-defaults') && write.body.flow === 'balanced'))
  assert.equal(await flow.inputValue(), 'off')
  assert.equal(await defaults.getByRole('button', { name: 'Save narrator defaults', exact: true }).isDisabled(), true)
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    for (const panel of [session, defaults]) {
      await panel.getByLabel('Narration flow', { exact: true }).scrollIntoViewIfNeeded()
      assert.equal(await panel.evaluate(node => node.scrollWidth > node.clientWidth), false)
    }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  }
  assert.deepEqual(await page.evaluate(() => window.narrationFlowFixture.unhandled), [])
  assert.deepEqual(errors, [])
  console.log('Narration flow legacy defaults, keyboard, save/retry, session switching, author defaults and mobile checks passed.')
} finally { await browser.close() }
