import assert from 'node:assert/strict'
import process from 'node:process'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1360, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const base = process.env.FRONTEND_URL || 'http://127.0.0.1:5204'
page.setDefaultTimeout(10000)
try {
  await page.goto(base + '/tests/browser/aiFix.html')
  const card = page.getByText('character_details_incomplete', { exact: true }).locator('xpath=ancestor::div[contains(@class,"rounded-2xl")][1]')
  await card.getByRole('button', { name: 'AI-Fix', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'AI Fix Suggestions' })
  await dialog.getByRole('button', { name: 'Retry', exact: true }).click()
  await dialog.getByText("Complete the character's outfit", { exact: true }).waitFor()
  const apply = dialog.getByRole('button', { name: 'Apply selected fix', exact: true })
  assert.equal(await apply.isDisabled(), true)
  await dialog.getByRole('checkbox').check()
  assert.equal(await apply.isEnabled(), true)
  await page.screenshot({ path: '/tmp/ai-fix-proposals.png', fullPage: true })
  await apply.click()
  await dialog.getByText('Invalid structured character or clothing proposal.', { exact: true }).waitFor()
  const regenerated = page.waitForRequest(request => request.url().endsWith('/suggest-fix'))
  await dialog.getByRole('button', { name: 'Retry', exact: true }).click()
  assert.equal((await regenerated).postDataJSON().force_refresh, true)
  await dialog.getByText("Complete the character's outfit", { exact: true }).waitFor()
  await apply.click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await page.locator('#applied-count').textContent(), '1')
  const saved = await page.evaluate(async () => {
    const token = sessionStorage.getItem('access_token')
    const response = await fetch('/api/adventures/ai-fix-fixture/editor/assets', { headers: { Authorization: `Bearer ${token}` } })
    return response.json()
  })
  const npc = saved.npcs.find(item => item.id === 'MARA')
  const garments = saved.objects.filter(item => item.item_type === 'WEARABLE')
  assert.equal(garments.length, 7)
  assert.equal(npc.visual_profile.worn.length, 7)
  assert.equal(npc.inventory.length, 7)
  const inner = garments.filter(item => item.metadata_json?.clothing?.underwear || item.clothing?.underwear)
  assert.deepEqual(inner.map(item => item.name).sort(), ['Red silk bra', 'Red silk briefs'])
  const reloaded = page.waitForResponse(response => response.url().endsWith('/editor/validation/latest'))
  await page.reload()
  const run = await (await reloaded).json()
  assert.equal(run.structural_findings.some(item => item.code === 'character_details_incomplete' && item.location === 'npc:MARA'), false)
  assert.equal(await page.locator('#notifications').textContent(), '')
  const audit = await page.request.get(base + '/api/ai-fix-fixture/audit')
  assert.equal((await audit.json()).model_calls, 3)
  assert.deepEqual(errors, [])
  console.log('AI Fix browser → real API → SQL checks passed: retry, review, seven garments including underwear, and reload.')
} finally {
  await browser.close()
}
