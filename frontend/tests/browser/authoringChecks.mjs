import assert from 'node:assert/strict'

export async function checkAuthoring(page, url) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(15000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(url + '?screen=create&mode=advanced')
  await page.getByRole('heading', { name: 'Generate Adventure', exact: true }).waitFor()
  await page.getByPlaceholder('Enter a title...', { exact: true }).fill('Coastal charts')
  await page.getByPlaceholder(/The Weaver will use this/).fill('Explore the archive and follow the missing coastal charts.')
  await page.getByRole('button', { name: 'RPG', exact: true }).click()
  await page.locator('select').first().selectOption('Russian')
  await page.getByRole('button', { name: 'Visual novel', exact: true }).click()
  await page.getByText(/character-led dialogue/).first().waitFor()
  await page.getByRole('button', { name: 'RPG', exact: true }).click()
  await page.getByRole('button', { name: 'BEGIN WEAVING', exact: true }).click()
  await page.waitForFunction(() => window.portalFixture.writes.some(write => write.path === '/adventures/'))
  const creation = await page.evaluate(() => window.portalFixture.writes.find(write => write.path === '/adventures/').body)
  assert.equal(creation.title, 'Coastal charts')
  assert.equal(creation.original_prompt, 'Explore the archive and follow the missing coastal charts.')
  assert.equal(creation.rule_enforcement_mode, 'rpg')
  assert.equal(creation.language, 'Russian')
  assert.equal(creation.selected_image_styles[0].id, 'watercolour')
  await page.getByRole('button', { name: 'Simple', exact: true }).click()
  assert.equal(await page.getByPlaceholder('Leave blank to automatically derive from your concept').inputValue(), 'Coastal charts')
  assert.equal(await page.getByPlaceholder(/^e.g. A forgotten star/).inputValue(), creation.original_prompt)
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  assert.equal(await page.getByPlaceholder('Enter a title...', { exact: true }).inputValue(), 'Coastal charts')
  await page.screenshot({ path: '/tmp/taleweaver-create-advanced-1440.png' })

  await page.goto(url + '?screen=editor')
  const nav = page.getByRole('navigation', { name: 'Adventure sections', exact: true })
  await nav.waitFor()
  assert.equal(await nav.getByRole('button').count(), 15)
  const labels = ['World', 'Living World', 'Sequences', 'Protagonist', 'Map', 'Scenes', 'Inhabitants', 'Items', 'Side Quests', 'Awards', 'Scripts', 'Visual Style', 'Tone', 'Advanced', 'Validation']
  for (const label of labels) {
    await nav.getByRole('button', { name: new RegExp('^' + label) }).click()
    await page.waitForTimeout(80)
    assert.ok((await page.locator('.authoring-content').innerText()).trim().length > 0, label)
  }
  await nav.getByRole('button', { name: 'World', exact: true }).click()
  await page.locator('.authoring-content').getByText('Letters from the Coast', { exact: true }).first().click()
  const title = page.locator('.authoring-content input[type="text"]:visible').first()
  await title.fill('Letters and lighthouse charts')
  await title.press('Enter')
  await page.waitForFunction(() => window.portalFixture.writes.some(write => write.method === 'PATCH' && write.path === '/adventures/coast' && write.body.title === 'Letters and lighthouse charts'))
  await nav.getByRole('button', { name: 'Scenes', exact: true }).click()
  await nav.getByRole('button', { name: 'World', exact: true }).click()
  await page.locator('.authoring-content').getByText('Letters and lighthouse charts', { exact: true }).first().waitFor()
  await page.screenshot({ path: '/tmp/taleweaver-editor-world-1440.png' })
  await nav.getByRole('button', { name: 'Map', exact: true }).click()
  assert.ok(await page.locator('svg marker').count() > 0)
  await page.screenshot({ path: '/tmp/taleweaver-editor-map-1440.png' })
  assert.deepEqual(await page.evaluate(() => window.portalFixture.unhandled), [])
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.locator('#editor-section').selectOption('inhabitants')
    await page.getByText('Mira', { exact: true }).first().waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(await page.locator('.adventure-editor-view').evaluate(node => node.scrollWidth > node.clientWidth), false)
    await page.screenshot({ path: `/tmp/taleweaver-editor-inhabitants-${width}.png` })
    await page.goto(url + '?screen=create&mode=advanced')
    await page.getByRole('heading', { name: 'Generate Adventure' }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(await page.locator('.adventure-create-view').evaluate(node => node.scrollWidth > node.clientWidth), false)
    await page.screenshot({ path: `/tmp/taleweaver-create-advanced-${width}.png` })
    await page.goto(url + '?screen=editor')
    await page.locator('#editor-section').selectOption('world')
  }
  assert.deepEqual(errors, [])
}
