import assert from 'node:assert/strict'
import process from 'node:process'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const base = process.env.FRONTEND_URL || 'http://127.0.0.1:5215'
const failures = []
const dialog = page => page.getByRole('dialog', { name: 'World Info', exact: true })
const button = (page, name) => page.locator('dialog[open]').getByRole('button', { name, exact: true })
async function check(name, action) {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.setDefaultTimeout(6000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.goto(`${base}/tests/browser/worldInfo.html?records=120`)
    await page.getByRole('button', { name: 'Session', exact: true }).click()
    await page.getByRole('menuitem', { name: /World Info/ }).click()
    await action(page)
    assert.deepEqual(errors, [])
    console.log(`PASS ${name}`)
  } catch (error) { failures.push(name); console.error(`FAIL ${name}: ${error.message}`) }
  finally { await page.close() }
}
try {
  await check('file upload occupies a single row above the source workspace', async page => {
    const upload = dialog(page).getByRole('form', { name: 'Add source material', exact: true })
    await upload.waitFor()
    const box = await upload.boundingBox(), workspace = await dialog(page).locator('.world-info-workspace').boundingBox()
    assert.ok(box.y + box.height <= workspace.y + 1)
    const bottoms = await upload.locator('input, select, button[type=submit]').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().bottom))
    assert.ok(Math.max(...bottoms) - Math.min(...bottoms) < 3)
    await dialog(page).getByRole('button', { name: /The coastal archive.*version/ }).click()
    await page.screenshot({ path: '/tmp/world-info-upload-row.png' })
  })
  await check('text authoring retains the exact source and starts the existing processing flow', async page => {
    await dialog(page).getByRole('tab', { name: 'New entry', exact: true }).click()
    const text = 'The eastern pier has a blue lantern.\n\nA coastal note. 🧭'
    await dialog(page).getByLabel('Source title', { exact: true }).fill('Eastern pier note')
    await dialog(page).getByLabel('Source text', { exact: true }).fill(text)
    await page.screenshot({ path: '/tmp/world-info-new-entry.png' })
    await dialog(page).getByRole('tab', { name: 'Review', exact: true }).click()
    await dialog(page).getByRole('tab', { name: 'New entry', exact: true }).click()
    assert.equal(await dialog(page).getByLabel('Source text', { exact: true }).inputValue(), text)
    await page.keyboard.press('Escape')
    await dialog(page).getByRole('heading', { name: 'Discard unsaved source text?', exact: true }).waitFor()
    await button(page, 'Keep current state').click()
    await button(page, 'Analyse text').click()
    await page.waitForFunction(() => document.querySelector('#world-info-tab-files')?.getAttribute('aria-selected') === 'true')
    await dialog(page).getByRole('heading', { name: 'Eastern pier note', exact: true }).waitFor()
    await button(page, 'View original source').click()
    assert.equal(await dialog(page).locator('pre').innerText(), text)
    const writes = await page.evaluate(() => window.worldInfoFixture.writes)
    assert.equal(writes.filter(value => value.path === '/sources').length, 1)
    assert.equal(writes.filter(value => value.path.endsWith('/process')).length, 1)
    await dialog(page).getByRole('tab', { name: 'New entry', exact: true }).click()
    assert.equal(await dialog(page).getByLabel('Source text', { exact: true }).inputValue(), '')
  })
  await check('page selection and all-page publication are visible and preserve version checks', async page => {
    await dialog(page).getByRole('tab', { name: 'Review', exact: true }).click()
    const selection = dialog(page).getByRole('region', { name: 'Select and publish entries', exact: true })
    await selection.getByRole('checkbox', { name: 'Select this page', exact: true }).check()
    await page.screenshot({ path: '/tmp/world-info-selection.png' })
    const count = await dialog(page).locator('.world-info-entry-table tbody tr').count()
    assert.equal(await dialog(page).locator('.world-info-entry-table tbody input:checked').count(), count)
    await dialog(page).locator('.world-info-entry-table tbody input').first().uncheck()
    assert.equal(await selection.getByRole('checkbox', { name: 'Select this page', exact: true }).evaluate(node => node.indeterminate), true)
    await selection.getByRole('checkbox', { name: 'Select this page', exact: true }).check()
    await button(page, `Publish selected (${count})`).click()
    await dialog(page).getByRole('heading', { name: 'Replace the accepted source version?', exact: true }).waitFor()
    await button(page, 'Keep current state').click()
    await button(page, 'Clear selection').click()
    assert.equal(await dialog(page).locator('.world-info-entry-table tbody input:checked').count(), 0)
    await dialog(page).getByLabel('Source version filter', { exact: true }).selectOption('revision-2')
    await selection.getByRole('button', { name: 'Publish all matching', exact: true }).click()
    await dialog(page).getByRole('region', { name: 'Bulk action preview', exact: true }).waitFor()
    const before = await page.evaluate(() => window.worldInfoFixture.writes.length)
    await button(page, 'Confirm matching changes').click()
    await dialog(page).getByRole('heading', { name: /Apply to .* matching entries/ }).waitFor()
    assert.equal(await page.evaluate(() => window.worldInfoFixture.writes.length), before)
    await button(page, 'Confirm').click()
    const body = await page.evaluate(() => window.worldInfoFixture.writes.find(value => value.path === '/entries/bulk/apply')?.body)
    assert.equal(body.action, 'publish'); assert.equal(body.filters.source_revision_id, 'revision-2')
    assert.ok(body.selection_hash)
  })
  await check('facts, original evidence and relationships do not require accordions', async page => {
    await dialog(page).getByRole('tab', { name: 'Review', exact: true }).click()
    await dialog(page).locator('[data-world-info-entry="entry-beacon"]').click()
    const entry = page.locator('.world-info-entry-dialog[open]')
    await entry.getByRole('heading', { name: 'Facts in this entry', exact: true }).waitFor()
    assert.equal(await entry.locator('.world-info-entry-dialog-body details').count(), 0)
    assert.equal(await entry.locator('blockquote').first().isVisible(), true)
    await button(page, 'Edit entry').click()
    await entry.getByLabel('Related entry', { exact: true }).waitFor()
    assert.equal(await entry.getByLabel('Related entry', { exact: true }).isVisible(), true)
    assert.equal(await entry.locator('.world-info-entry-dialog-body details').count(), 0)
    await page.screenshot({ path: '/tmp/world-info-open-evidence.png' })
  })
  assert.deepEqual(failures, [])
} finally { await browser.close() }
