import assert from 'node:assert/strict'

async function section(page, name, key) {
  const nav = page.getByRole('navigation', { name: 'Adventure sections', includeHidden: true })
  await nav.waitFor({ state: 'attached' })
  if (await nav.isVisible()) await nav.getByRole('button', { name, exact: true }).click()
  else await page.locator('#editor-section').selectOption(key)
}

async function npcMenu(page) {
  await page.locator('.authoring-content button[class*="group/dots"]').first().click()
}

async function bounds(panel, page) {
  await panel.waitFor()
  const rect = await panel.boundingBox()
  const viewport = page.viewportSize()
  assert.ok(rect.x >= 0 && rect.y >= 0 && rect.x + rect.width <= viewport.width + 1 && rect.y + rect.height <= viewport.height + 1, JSON.stringify({ rect, viewport }))
  assert.equal(await panel.evaluate(node => node.scrollWidth > node.clientWidth + 1), false, 'dialog horizontal overflow')
}

export async function checkAuthoringDialogs(page, url) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(15000)
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 720, height: 500 }, { width: 320, height: 568 }]) {
    await page.setViewportSize(viewport)
    await page.goto(url + '?screen=editor')
    await section(page, 'Inhabitants', 'inhabitants')
    await npcMenu(page)
    await page.getByRole('button', { name: 'Edit Details', exact: true }).click()
    const panel = page.locator('.entity-editor-dialog')
    await bounds(panel, page)
    await panel.getByLabel('Entity name', { exact: true }).fill('Mira the archivist')
    const story = panel.locator('.entity-field-group').filter({ has: page.locator('summary', { hasText: 'Character & goals' }) })
    await story.locator('textarea').first().fill('Find the coastal charts before the archive closes.')
    await panel.getByRole('button', { name: 'Details · Personality', exact: true }).click()
    const personality = page.locator('dialog[open]')
    await bounds(personality, page)
    await personality.getByLabel('Openness', { exact: false }).selectOption('curious')
    await personality.getByRole('button', { name: 'Use traits', exact: true }).click()
    await personality.waitFor({ state: 'hidden' })
    await panel.getByRole('button', { name: 'Details · Personality', exact: true }).click()
    await personality.getByLabel('Openness', { exact: false }).selectOption('cautious')
    await page.keyboard.press('Escape')
    await personality.waitFor({ state: 'hidden' })
    await panel.getByRole('button', { name: 'Rules & scripts', exact: true }).click()
    await panel.getByRole('button', { name: 'Details', exact: true }).click()
    assert.equal(await panel.getByLabel('Entity name', { exact: true }).inputValue(), 'Mira the archivist')
    await panel.getByRole('button', { name: 'Apply Changes', exact: true }).click()
    await panel.waitFor({ state: 'hidden' })
    const saved = await page.evaluate(() => window.portalFixture.writes.find(write => write.path.endsWith('/editor/entity') && write.method === 'PATCH').body)
    assert.equal(saved.target_type, 'npc')
    assert.equal(saved.target_id, 'MIRA')
    assert.equal(saved.name, 'Mira the archivist')
    assert.equal(saved.goal, 'Find the coastal charts before the archive closes.')
    assert.equal(saved.character, 'Curious, methodical and quietly welcoming.')
    assert.equal(saved.description, 'The patient keeper of the old archive.')
    assert.equal(saved.personality_profile.openness, 'curious')
    await npcMenu(page)
    await page.getByRole('button', { name: 'Edit Details', exact: true }).click()
    assert.equal(await panel.getByLabel('Entity name', { exact: true }).inputValue(), saved.name)
    await panel.getByLabel('Entity name', { exact: true }).fill('Discard this change')
    const writesBeforeCancel = await page.evaluate(() => window.portalFixture.writes.length)
    await panel.getByRole('button', { name: 'Discard', exact: true }).click()
    assert.equal(await page.evaluate(() => window.portalFixture.writes.length), writesBeforeCancel)
    await npcMenu(page)
    await page.getByRole('button', { name: 'Edit Details', exact: true }).click()
    assert.equal(await panel.getByLabel('Entity name', { exact: true }).inputValue(), saved.name)
    await page.screenshot({ path: `/tmp/taleweaver-npc-editor-${viewport.width}.png` })
    await panel.getByRole('button', { name: 'Discard', exact: true }).click()

    await section(page, 'Items', 'items')
    await page.getByRole('button', { name: 'Actions for Sealed letter', exact: true }).click()
    await page.getByRole('button', { name: 'Edit Details', exact: true }).click()
    await bounds(panel, page)
    const properties = panel.locator('.entity-field-group').filter({ has: page.locator('summary', { hasText: 'Item properties' }) })
    assert.ok(await properties.locator('textarea').count() > 0)
    await panel.getByLabel('Entity name', { exact: true }).fill('Lighthouse letter')
    await panel.getByRole('button', { name: 'Apply Changes', exact: true }).click()
    await panel.waitFor({ state: 'hidden' })
    const item = await page.evaluate(() => window.portalFixture.writes.filter(write => write.path.endsWith('/editor/entity') && write.method === 'PATCH').at(-1).body)
    assert.equal(item.target_id, 'LETTER')
    assert.equal(item.item_type, 'READABLE')
    assert.equal(item.name, 'Lighthouse letter')
    assert.equal(item.text_log_content, 'Meet me by the lighthouse after the archive closes.')
    await page.getByRole('button', { name: 'Actions for Lighthouse letter', exact: true }).click()
    await page.getByRole('button', { name: 'Edit Details', exact: true }).click()
    await page.screenshot({ path: `/tmp/taleweaver-item-editor-${viewport.width}.png` })
    await panel.getByRole('button', { name: 'Discard', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.portalFixture.unhandled), [])
  }
  assert.deepEqual(errors, [])
}
