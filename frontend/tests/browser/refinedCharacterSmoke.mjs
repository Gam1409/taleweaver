import assert from 'node:assert/strict'
import process from 'node:process'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto((process.env.FRONTEND_URL || 'http://127.0.0.1:5203') + '/tests/browser/groupedActions.html?mode=vn')
  await page.getByRole('button', { name: 'World', exact: true }).click()
  await page.getByRole('menuitem', { name: /^Characters/ }).click()
  await page.getByRole('dialog', { name: 'Characters', exact: true }).getByRole('button', { name: /^Mira/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Mira — Character', exact: true })
  await dialog.getByRole('tab', { name: 'Overview', exact: true }).waitFor()
  assert.equal(await dialog.getByRole('tab', { name: 'Overview', exact: true }).getAttribute('aria-selected'), 'true')
  await dialog.getByRole('region', { name: 'About this character', exact: true }).waitFor()
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 })
    await dialog.getByRole('tab', { name: 'Overview', exact: true }).click()
    const box = await dialog.boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= width && box.y >= 0 && box.y + box.height <= page.viewportSize().height)
    assert.equal(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth), true)
    await page.screenshot({ path: `/tmp/taleweaver-refined-overview-${width}.png` })
    await dialog.getByRole('tab', { name: 'State & clothing', exact: true }).click()
    await dialog.getByRole('region', { name: 'Clothing and physical condition', exact: true }).waitFor()
    assert.equal(await dialog.getByRole('button', { name: 'Neck', exact: true }).count(), 0)
    await dialog.getByRole('checkbox', { name: 'Show empty slots', exact: true }).check()
    assert.equal(await dialog.getByRole('button', { name: 'Neck', exact: true }).count(), 1)
    await dialog.getByRole('checkbox', { name: 'Show empty slots', exact: true }).uncheck()
    const overview = dialog.locator('[data-general-overview]')
    assert.equal(await overview.getAttribute('open'), null)
    assert.equal(await overview.evaluate(node => node.previousElementSibling.querySelector('summary').textContent.trim()), 'Character card display')
    await overview.locator('summary').click()
    await overview.getByText('Mira keeps the archive and its coastal charts.', { exact: true }).waitFor()
    await overview.locator('summary').click()
    await page.screenshot({ path: `/tmp/taleweaver-refined-state-${width}.png` })
  }
  await dialog.getByRole('tab', { name: 'Overview', exact: true }).click()
  await page.keyboard.press('ArrowRight')
  assert.equal(await dialog.getByRole('tab', { name: 'State & clothing', exact: true }).getAttribute('aria-selected'), 'true')
  await page.keyboard.press('End')
  await dialog.getByRole('tab', { name: /^History with your character/ }).click()
  await dialog.getByText('Mira showed Alex the sealed letter.', { exact: true }).first().waitFor()
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  assert.deepEqual(errors, [])
  console.log('PASS: refined card overview, original state/history, optional empty slots, collapsed general overview after display preferences, keyboard and mobile bounds.')
} finally { await browser.close() }
