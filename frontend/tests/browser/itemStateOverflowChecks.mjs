import assert from 'node:assert/strict'

export async function checkItemStateOverflow(page, url) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(10000)
  for (const width of [1440, 390, 320, 800]) {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : width === 800 ? 420 : 568 })
    await page.goto(url)
    await page.getByRole('button', { name: 'Inspect flask', exact: true }).hover()
    const state = page.getByRole('region', { name: 'Current item state', exact: true })
    await state.waitFor()
    await page.waitForTimeout(400)
    const card = page.getByRole('region', { name: 'Coastal flask details', exact: true })
    const bounds = await card.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= 0 && bounds.y + bounds.height <= page.viewportSize().height, 'All item details must be inside a bounded readable surface')
    const values = await page.evaluate(() => window.overflowFixture.item.current_state.map(fact => fact.detail))
    assert.equal(values.length, 12)
    assert.ok(values.every(value => value.length === 320))
    for (const value of values) await state.getByText(value, { exact: true }).waitFor()
    assert.equal(await state.locator('script').count(), 0)
    assert.equal(await page.evaluate(() => window.executed), undefined)
    assert.equal(await card.locator('img').count(), 1)
    await page.getByRole('button', { name: 'Inspect flask', exact: true }).click()
    assert.equal(await page.getByLabel('Source activations', { exact: true }).textContent(), '1', 'The popup must not intercept the original trigger action')
    await card.hover({ position: { x: bounds.width / 2, y: Math.min(100, bounds.height / 2) } })
    await page.waitForTimeout(400)
    await card.waitFor()
    await page.mouse.wheel(0, 5000)
    await page.waitForFunction(() => { const node = document.querySelector('.game-hover-scroll'); return node && node.scrollTop > 0 })
    const end = await card.getByText('2 STA', { exact: true }).boundingBox()
    assert.ok(end.y >= bounds.y && end.y + end.height <= bounds.y + bounds.height + 1, 'Original mechanics must remain readable after scrolling')
    assert.equal(await card.getByText(/Original description:/).count(), 1)
    assert.equal(await state.locator('p').count(), 13)
    await card.evaluate(node => { node.scrollTop = 0 })
    await page.getByRole('button', { name: 'Close entity details', exact: true }).focus()
    await page.keyboard.press('Tab')
    assert.equal(await card.evaluate(node => node === document.activeElement), true)
    await page.keyboard.press('PageDown')
    await page.waitForFunction(() => document.querySelector('.game-hover-scroll').scrollTop > 0)
    await page.mouse.move(width - 1, 1)
    await page.waitForTimeout(400)
    await card.waitFor()
    await page.keyboard.press('Escape')
    await card.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Inspect flask', exact: true }).hover()
    await card.waitFor()
    await page.getByRole('button', { name: 'Outside action', exact: true }).click()
    assert.equal(await page.getByLabel('Outside activations', { exact: true }).textContent(), '1')
    await card.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Inspect flask', exact: true }).hover()
    await card.waitFor()
    await page.evaluate(() => window.overflowFixture.openNative())
    const independent = page.getByRole('dialog', { name: 'Independent dialog', exact: true })
    await independent.waitFor()
    await page.mouse.move(width - 1, 1)
    await page.keyboard.press('Escape')
    await independent.waitFor({ state: 'hidden' })
    await card.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Open container', exact: true }).click()
    const container = page.getByRole('heading', { name: 'Coastal chest', exact: true })
    const source = page.getByTitle('Take Coastal flask', { exact: true })
    await source.hover()
    await card.waitFor()
    await source.click()
    assert.equal(await page.getByLabel('Source activations', { exact: true }).textContent(), '2')
    await card.focus()
    await page.keyboard.press('Escape')
    await card.waitFor({ state: 'hidden' })
    await container.waitFor()
    await page.keyboard.press('Escape')
    await container.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Inspect flask', exact: true }).hover()
    await card.waitFor()
    await page.getByRole('button', { name: 'Close entity details', exact: true }).click()
    await card.waitFor({ state: 'hidden' })
  }
  const cdp = await page.context().newCDPSession(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(url)
  await cdp.send('Emulation.setPageScaleFactor', { pageScaleFactor: 2 })
  await page.getByRole('button', { name: 'Inspect flask', exact: true }).hover()
  const card = page.getByRole('region', { name: 'Coastal flask details', exact: true })
  await card.waitFor()
  await page.waitForTimeout(400)
  assert.equal(await card.evaluate(node => {
    const box = node.getBoundingClientRect(), viewport = visualViewport
    return viewport.scale === 2 && box.x >= viewport.offsetLeft && box.right <= viewport.offsetLeft + viewport.width && box.y >= viewport.offsetTop && box.bottom <= viewport.offsetTop + viewport.height
  }), true, 'The actual 200% visual viewport must contain the popup')
  await card.hover()
  await page.mouse.wheel(0, 5000)
  await page.waitForFunction(() => document.querySelector('.game-hover-scroll').scrollTop > 0)
  await page.getByRole('button', { name: 'Close entity details', exact: true }).click()
  await card.waitFor({ state: 'hidden' })
  await cdp.send('Emulation.setPageScaleFactor', { pageScaleFactor: 1 })
  assert.deepEqual(errors, [])
}
