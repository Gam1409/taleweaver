import assert from 'node:assert/strict'

export async function checkPortalWorkspace(page, url) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(15000)
  const button = name => page.getByRole('button', { name, exact: typeof name === 'string' })
  const section = name => page.getByRole('navigation', { name: 'Workspace', exact: true }).getByRole('button', { name, exact: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(url)
  await page.getByRole('heading', { name: 'Library', exact: true }).waitFor()
  await button('Grid view').click()
  await page.getByRole('searchbox', { name: 'Search adventures' }).fill('observatory')
  await page.getByText('Showing 1 of 3 adventures', { exact: true }).waitFor()
  await button('Reset filters').click()
  await page.getByLabel('Filter by game mode').selectOption('vn')
  await page.getByText('Showing 1 of 3 adventures', { exact: true }).waitFor()
  await button('Reset filters').click()
  await button('Table view').click()
  assert.equal(await page.locator('tbody tr').count(), 3)
  await button(/^Manage/).focus()
  await page.keyboard.press('ArrowDown')
  assert.match(await page.evaluate(() => document.activeElement.textContent), /Update all/)
  await page.keyboard.press('Escape')
  assert.equal(await button(/^Manage/).evaluate(el => el === document.activeElement), true)
  await button(/^Manage/).click()
  await page.getByRole('menuitem', { name: /Delete all adventures/ }).click()
  await page.getByRole('heading', { name: 'Delete all adventures', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.portalFixture.requests.some(p => p.startsWith('DELETE'))), false)
  await button('Cancel').click()
  await button('Import samples').click()
  await page.getByRole('heading', { name: 'Seed Library', exact: true }).waitFor()
  await button('Cancel').click()

  await section('Sessions').click()
  await page.getByRole('heading', { name: 'Game sessions', exact: true }).waitFor()
  await button('Table view').click()
  await page.getByTitle('Edit Status Note', { exact: true }).first().click()
  await page.locator('textarea').fill('Compare the lighthouse charts.')
  await button(/Save Note/).click()
  await page.getByRole('heading', { name: 'Session Note', exact: true }).waitFor({ state: 'hidden' })
  assert.ok(await page.evaluate(() => window.portalFixture.requests.includes('PATCH /adventures/sessions/coast-session')))
  await button(/^Manage/).click()
  assert.equal(await page.getByRole('menuitem', { name: /Restore defaults/ }).count(), 0)
  await page.keyboard.press('Escape')

  await section('Profile').click()
  await page.getByRole('tab', { name: /Trophies/ }).click()
  await page.getByText(/Your trophy room is empty/).waitFor()
  await page.getByRole('tab', { name: /Account/ }).click()
  await page.locator('#profile-language').selectOption('Russian')
  await page.waitForFunction(() => window.portalFixture.user.default_language === 'Russian')
  assert.equal(await page.evaluate(() => document.documentElement.style.getPropertyValue('--session-font')), '')
  await button('About Archive').click()
  await button(/Close Archive/).click()

  await section('Administration').click()
  const adminButtons = page.locator('aside nav button')
  assert.equal(await adminButtons.count(), 10)
  for (let index = 0; index < 10; index++) {
    await adminButtons.nth(index).click()
    await page.waitForTimeout(60)
    assert.ok((await page.locator('main h1').first().textContent()).trim())
  }
  await button('Return to Portal').click()
  await button('Grid view').click()
  await page.screenshot({ path: '/tmp/taleweaver-portal-desktop.png' })

  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await button('Open menu').click()
    await page.getByRole('dialog', { name: 'Workspace menu' }).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await button('Open menu').evaluate(el => el === document.activeElement), true)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await button(/^Manage/).click()
    const box = await page.getByRole('menu', { name: /Manage/ }).boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= width)
    await page.keyboard.press('Escape')
    await page.screenshot({ path: `/tmp/taleweaver-portal-${width}.png` })
    await button('Open menu').click()
    await section('Administration').click()
    await page.locator('#admin-section').selectOption('game')
    await page.getByRole('heading', { name: 'Game Preferences' }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await button('Return to Portal').click()
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await button('New adventure').click()
  await button('Save world blueprint').waitFor()
  await page.waitForFunction(() => window.portalFixture.requests.some(path => path.endsWith('/world-brief')))
  assert.equal(await page.evaluate(() => document.documentElement.hasAttribute('data-workspace-theme')), true)
  assert.deepEqual(await page.evaluate(() => window.portalFixture.unhandled), [])
  await page.goto(url)
  await button('Generate world').click()
  await page.getByRole('heading', { name: 'Generate Adventure', exact: true }).waitFor()
  assert.deepEqual(await page.evaluate(() => window.portalFixture.unhandled), [])
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(url + (url.includes('?') ? '&' : '?') + 'role=user')
  await button('Open menu').click()
  assert.equal(await section('Administration').count(), 0)
  await page.keyboard.press('Escape')
  assert.deepEqual(errors, [])
}
