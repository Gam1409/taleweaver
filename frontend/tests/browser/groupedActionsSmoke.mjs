import assert from 'node:assert/strict'
import process from 'node:process'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.setDefaultTimeout(10000)
const menu = name => page.getByRole('menu', { name, exact: true })
const trigger = name => page.getByRole('button', { name, exact: true })
try {
  await page.goto((process.env.FRONTEND_URL || 'http://127.0.0.1:5203') + '/tests/browser/groupedActions.html')
  await page.locator('.game-action-bar').waitFor()
  const draft = page.getByPlaceholder('What do you do next?')
  await draft.fill('Keep this unfinished action.')
  await trigger('World').click()
  await menu('World').getByRole('menuitem', { name: /World map/ }).click()
  await page.getByText('World Map', { exact: true }).waitFor()
  assert.ok(await page.locator('svg marker#arrow-oneway').count())
  await page.getByTitle('Close', { exact: true }).click()
  await trigger('World').focus()
  await page.keyboard.press('ArrowDown')
  assert.match(await page.evaluate(() => document.activeElement.textContent), /Hero & inventory/)
  await page.keyboard.press('End')
  assert.match(await page.evaluate(() => document.activeElement.textContent), /Characters/)
  await page.keyboard.press('Escape')
  assert.equal(await trigger('World').evaluate(el => el === document.activeElement), true)
  await trigger('Response').click()
  await menu('Response').getByRole('menuitem', { name: 'Narration versions', exact: true }).click()
  const versions = page.getByRole('dialog', { name: 'Narration versions', exact: true })
  await versions.waitFor()
  assert.equal(await menu('Response').isVisible(), false)
  await versions.getByRole('button', { name: 'Close', exact: true }).click()
  await trigger('Response').click()
  await menu('Response').getByRole('menuitem', { name: 'Correct the narrator', exact: true }).click()
  const correction = page.getByRole('dialog', { name: 'Narrator correction', exact: true })
  await correction.waitFor()
  assert.equal(await menu('Response').isVisible(), false)
  await page.keyboard.press('Escape')
  await trigger('Response').click()
  await menu('Response').getByRole('menuitem', { name: /Undo turn/ }).waitFor()
  page.once('dialog', dialog => dialog.dismiss())
  await menu('Response').getByRole('menuitem', { name: /Undo turn/ }).click()
  assert.equal(await page.evaluate(() => window.groupedActionsFixture.events.includes('undo')), false)
  await trigger('Response').click()
  page.once('dialog', dialog => dialog.accept())
  await menu('Response').getByRole('menuitem', { name: /Regenerate turn/ }).click()
  assert.equal(await page.evaluate(() => window.groupedActionsFixture.events.includes('replay')), true)
  const checks = await page.evaluate(() => window.groupedActionsFixture.requests.filter(url => url.endsWith('/chat/replay')).length)
  await trigger('Response').click()
  await page.keyboard.press('Escape')
  await trigger('Response').click()
  assert.equal(await page.evaluate(() => window.groupedActionsFixture.requests.filter(url => url.endsWith('/chat/replay')).length), checks)
  await page.keyboard.press('Escape')
  await page.evaluate(() => { window.groupedActionsFixture.setReplayFailure(true); window.groupedActionsFixture.refreshReplayCheck() })
  await trigger('Response').click()
  await menu('Response').getByRole('menuitem', { name: 'Retry turn check', exact: true }).waitFor()
  await page.evaluate(() => window.groupedActionsFixture.setReplayFailure(false))
  await menu('Response').getByRole('menuitem', { name: 'Retry turn check', exact: true }).click()
  await menu('Response').getByRole('menuitem', { name: /Regenerate turn/ }).waitFor()
  assert.equal(await menu('Response').isVisible(), true)
  await trigger('World').click()
  assert.equal(await menu('Response').isVisible(), false)
  await trigger('Ideas').click()
  assert.equal(await menu('World').isVisible(), false)
  await trigger('Story').click()
  await page.getByText('Action Ideas', { exact: true }).waitFor({ state: 'hidden' })
  await page.keyboard.press('Escape')
  assert.equal(await draft.inputValue(), 'Keep this unfinished action.')
  await page.evaluate(() => window.groupedActionsFixture.setBusy(true))
  await trigger('Response').click()
  assert.equal(await menu('Response').getByRole('menuitem', { name: /Regenerate turn/ }).isDisabled(), true)
  assert.equal(await menu('Response').getByRole('menuitem', { name: 'Regenerate last response', exact: true }).isDisabled(), true)
  await page.keyboard.press('Escape')
  await page.evaluate(() => { window.groupedActionsFixture.setBusy(false); window.groupedActionsFixture.setDebug(false); window.groupedActionsFixture.setMode('vn') })
  await trigger('World').click()
  await menu('World').getByRole('menuitem', { name: /Profile & inventory/ }).waitFor()
  await trigger('Story').click()
  assert.equal(await menu('Story').getByRole('menuitem', { name: /Quests/ }).count(), 0)
  assert.equal(await trigger('Tools').count(), 0)
  await trigger('Response').click()
  assert.equal(await menu('Response').getByRole('menuitem', { name: /Undo turn/ }).count(), 0)
  await page.keyboard.press('Escape')
  await page.evaluate(() => { window.groupedActionsFixture.setDebug(true); window.groupedActionsFixture.setMode('rpg') })
  await page.waitForTimeout(250)
  await page.screenshot({ path: '/tmp/taleweaver-existing-groups-desktop.png' })
  for (const name of ['World', 'Story', 'Response', 'Tools']) {
    await trigger(name).click()
    await page.waitForTimeout(250)
    await page.screenshot({ path: `/tmp/taleweaver-existing-groups-${name.toLowerCase()}.png` })
    await page.keyboard.press('Escape')
  }
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    for (const name of ['World', 'Story', 'Response', 'Tools']) {
      assert.equal(await trigger(name).isVisible(), true)
      await trigger(name).click()
      const bounds = await menu(name).boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1)
      assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= 844)
      await page.keyboard.press('Escape')
    }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `/tmp/taleweaver-existing-groups-mobile-${width}.png` })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await trigger('World').click()
  const duration = await menu('World').evaluate(el => getComputedStyle(el).transitionDuration)
  assert.ok(parseFloat(duration) < .01)
  assert.deepEqual(errors, [])
  console.log('Grouped actions: existing map, keyboard navigation, detached dialogs, undo confirmation, replay, stable snapshot checks, single popup, draft retention, locks, VN/Debug gates, 320/390px menus and reduced motion passed.')
} finally {
  await browser.close()
}
