import assert from 'node:assert/strict'
import process from 'node:process'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const base = process.env.FRONTEND_URL || 'http://127.0.0.1:5203'
const card = () => page.getByRole('dialog', { name: 'Mira — Character', exact: true })
try {
  await page.goto(base + '/tests/browser/groupedActions.html?mode=vn')
  await page.getByRole('button', { name: 'Change portrait of Mira', exact: true }).click()
  await card().getByRole('region', { name: 'Clothing and physical condition', exact: true }).waitFor()
  await card().getByRole('button', { name: /^Chest: Work jacket/ }).focus()
  await page.getByRole('tooltip').waitFor()
  assert.match(await page.getByRole('tooltip').textContent(), /Work jacket/)
  assert.match(await page.getByRole('tooltip').textContent(), /Linen shirt/)
  await card().getByRole('tab', { name: 'History', exact: true }).click()
  await card().getByText('Mira keeps the archive and its coastal charts.', { exact: true }).first().waitFor()
  await card().getByRole('tab', { name: /^History with your character/ }).click()
  await card().getByText('Mira showed Alex the sealed letter.', { exact: true }).first().waitFor()
  await card().getByRole('tab', { name: 'State & clothing', exact: true }).click()
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 })
    const bounds = await card().boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width)
    assert.equal(await card().evaluate(node => node.scrollWidth <= node.clientWidth), true)
    await page.screenshot({ path: `/tmp/taleweaver-character-card-${width}.png` })
  }
  await card().getByRole('button', { name: 'Close character', exact: true }).click()
  await page.getByRole('button', { name: 'World', exact: true }).click()
  await page.getByRole('menuitem', { name: /^Characters/ }).click()
  const directory = page.getByRole('dialog', { name: 'Characters', exact: true })
  await directory.getByRole('button', { name: /^Mira/ }).click()
  await card().getByRole('tab', { name: 'State & clothing', exact: true }).waitFor()
  await card().getByRole('button', { name: 'Close character', exact: true }).click()
  await directory.getByRole('button', { name: 'Close characters', exact: true }).click()
  await page.goto(base + '/tests/browser/groupedActions.html?mode=vn&panel=settings')
  const settings = page.getByRole('dialog', { name: 'Session settings', exact: true })
  await settings.getByRole('tab', { name: /Characters/ }).click()
  const personality = settings.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^NPC Personality/ }) })
  await personality.locator('summary').first().click()
  await personality.getByRole('combobox', { name: /^Mode\b/ }).selectOption('live')
  await personality.getByRole('checkbox', { name: 'Mira', exact: true }).check()
  await personality.getByRole('checkbox', { name: 'Owen', exact: true }).check()
  await personality.getByLabel('If NPC analysis fails', { exact: false }).selectOption('strict')
  await personality.getByLabel('Concurrent NPC analyses (experimental)', { exact: false }).selectOption('2')
  await personality.locator('summary').filter({ hasText: /^Request limits$/ }).click()
  await personality.getByLabel('Requests per turn', { exact: false }).fill('8')
  await settings.getByRole('tab', { name: /Memory & audio/ }).click()
  await settings.getByRole('tab', { name: /Characters/ }).click()
  assert.equal(await personality.getByRole('combobox', { name: /^Mode\b/ }).inputValue(), 'live')
  assert.equal(await personality.getByRole('checkbox', { name: 'Owen', exact: true }).isChecked(), true)
  await settings.getByRole('button', { name: 'Save Settings', exact: true }).click()
  await settings.waitFor({ state: 'hidden' })
  const write = await page.evaluate(() => window.groupedActionsFixture.settingsWrites.find(item => item.endpoint === 'chpm'))
  assert.deepEqual(write.body.settings.actor_ids, ['MIRA', 'OWEN'])
  assert.equal(write.body.settings.mode, 'live')
  assert.equal(write.body.settings.failure_policy, 'strict')
  assert.equal(write.body.settings.npc_concurrency, 2)
  await page.getByRole('button', { name: 'Session', exact: true }).click()
  await page.getByRole('menuitem', { name: /^Session settings/ }).click()
  await settings.getByRole('tab', { name: /Characters/ }).click()
  await settings.locator('summary').filter({ hasText: /^NPC Personality/ }).click()
  assert.equal(await settings.getByRole('combobox', { name: /^Mode\b/ }).inputValue(), 'live')
  assert.equal(await settings.getByRole('checkbox', { name: 'Mira', exact: true }).isChecked(), true)
  await page.screenshot({ path: '/tmp/taleweaver-personality-settings-320.png' })
  assert.deepEqual(errors, [])
  console.log('PASS: original character card, clothing layers, condition observations, both history tabs, directory, mobile bounds and NPC Personality draft/save/reopen for two actors.')
} finally { await browser.close() }
