import assert from 'node:assert/strict'
import process from 'node:process'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const base = process.env.FRONTEND_URL || 'http://127.0.0.1:5203'
try {
  await page.goto(base + '/tests/browser/groupedActions.html?mode=vn')
  await page.getByRole('navigation', { name: 'Preview mode' }).getByRole('link', { name: 'Visual mode', exact: true }).waitFor()
  assert.equal(await page.getByRole('link', { name: 'Visual mode', exact: true }).getAttribute('aria-current'), 'page')
  assert.equal(await page.locator('.header-experience').count(), 0)
  assert.equal(await page.locator('.header-quest').count(), 0)
  assert.equal(await page.locator('.emotion-portrait').count(), 3)
  await page.getByRole('region', { name: 'Moment illustration' }).getByText('Image generation is not connected in this preview.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'World', exact: true }).click()
  await page.getByRole('menuitem', { name: /^Profile & inventory/ }).click()
  await page.getByRole('button', { name: 'Appearance', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Equipment', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Story', exact: true }).click()
  assert.equal(await page.getByRole('menuitem', { name: /^Quests/ }).count(), 0)
  await page.keyboard.press('Escape')
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `/tmp/taleweaver-visual-chat-${width}.png` })
  }
  await page.goto(base + '/tests/browser/groupedActions.html?mode=vn&panel=settings')
  const dialog = page.getByRole('dialog', { name: 'Session settings', exact: true })
  await dialog.locator('summary').filter({ hasText: /^Visual novel narration$/ }).click()
  await dialog.getByRole('radio', { name: /^Brisk/ }).waitFor()
  await dialog.getByRole('tab', { name: /Characters/ }).click()
  await dialog.locator('summary').filter({ hasText: /^NPC Personality/ }).waitFor()
  await page.screenshot({ path: '/tmp/taleweaver-visual-settings-320.png' })
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  const rpgHref = await page.getByRole('link', { name: 'RPG', exact: true }).getAttribute('href')
  assert.equal(new URLSearchParams(rpgHref.slice(1)).get('panel'), 'settings')
  await page.getByRole('link', { name: 'RPG', exact: true }).click()
  await page.getByRole('dialog', { name: 'Session settings', exact: true }).waitFor()
  assert.equal(await page.locator('summary').filter({ hasText: /^Visual novel narration$/ }).count(), 0)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal(await page.locator('.header-experience').count(), 1)
  assert.equal(await page.locator('.header-quest').count(), 1)
  assert.deepEqual(errors, [])
  console.log('PASS: direct Visual mode, matching profile mode, original mode gates, three participants, settings deep link, mode navigation and responsive bounds.')
} finally { await browser.close() }
