import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/api/adventures/living-world/capabilities', route => route.fulfill({ json: { concordia_available: true, inference_serialization_enabled: true } }))
const preferences = async () => JSON.parse(await page.locator('#preferences').textContent())
try {
  await page.goto((process.env.FRONTEND_URL || 'http://127.0.0.1:5179') + '/tests/browser/concordiaSettings.html')
  assert.equal(await page.getByRole('button', { name: /Living World/ }).count(), 0)
  await page.getByRole('button', { name: 'Visual novel', exact: true }).click()
  await page.getByRole('button', { name: /Living World/ }).first().click()
  await page.getByRole('dialog').waitFor()
  assert.equal(await page.getByRole('slider').count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Apply settings' }).isDisabled(), true)
  await page.getByRole('checkbox', { name: 'Enable Concordia', exact: true }).check()
  assert.equal(await page.getByRole('slider').count(), 9)
  const slider = page.getByRole('slider', { name: 'Requests per batch', exact: true })
  await slider.fill('3')
  await page.getByRole('button', { name: 'Help: Requests per batch', exact: true }).hover()
  await page.getByRole('tooltip').filter({ hasText: 'at most one Utility' }).waitFor()
  await page.getByRole('button', { name: 'Apply settings' }).click()
  assert.equal((await preferences()).max_decisions_per_run, 3)
  assert.equal((await preferences()).decision_engine, 'concordia')
  assert.equal((await preferences()).living_world_enabled, true)
  await page.getByRole('button', { name: /Living World/ }).last().click()
  await page.getByText('Changes apply to new sessions only.', { exact: false }).waitFor()
  await page.getByRole('checkbox', { name: 'Enable Concordia', exact: true }).uncheck()
  assert.equal(await page.getByRole('slider').count(), 0)
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  assert.equal((await preferences()).living_world_enabled, false)
  assert.equal((await preferences()).deliberation_enabled, false)
  assert.equal(await page.locator('#saved').textContent(), '1')
  await page.getByRole('button', { name: /Living World/ }).last().click()
  await page.getByRole('checkbox', { name: 'Enable Concordia', exact: true }).check()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal((await preferences()).living_world_enabled, false)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: /Living World/ }).last().click()
  await page.getByRole('checkbox', { name: 'Enable Concordia', exact: true }).check()
  await page.getByRole('button', { name: 'Help: Enable Concordia', exact: true }).click()
  const tooltip = page.getByRole('tooltip')
  await tooltip.waitFor()
  const bounds = await tooltip.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390)
  await page.getByRole('button', { name: 'Help: Enable Concordia', exact: true }).press('Escape')
  await page.screenshot({ path: '/tmp/concordia-settings-mobile.png' })
  assert.equal(await page.getByRole('dialog').count(), 1)
  await page.getByRole('button', { name: 'Close Living World' }).press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: VN visibility, master checkbox, 9 sliders, save, cancel, persisted disabled state, hover/click help, mobile bounds and Escape.')
} finally { await browser.close() }
