import assert from 'node:assert/strict'
import process from 'node:process'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(12000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const base = process.env.FRONTEND_URL || 'http://127.0.0.1:5215'
const dialog = () => page.getByRole('dialog', { name: 'World Info', exact: true })
const button = name => dialog().getByRole('button', { name, exact: true })
async function open(records = 3) {
  await page.goto(`${base}/tests/browser/worldInfo.html?records=${records}`)
  await page.getByRole('button', { name: 'Session', exact: true }).click()
  await page.getByRole('menuitem', { name: /World Info/ }).click()
  await dialog().getByRole('tab', { name: 'Review', exact: true }).click()
  await dialog().locator('[data-world-info-entry]').first().waitFor()
}
async function geometry() {
  const measurements = await dialog().evaluate(node => {
    const bounds = node.getBoundingClientRect(), body = node.querySelector('.world-info-body').getBoundingClientRect()
    const results = node.querySelector('.world-info-catalog-results')?.getBoundingClientRect()
    return { fits: node.scrollWidth <= node.clientWidth && bounds.left >= visualViewport.offsetLeft - 1 && bounds.right <= visualViewport.offsetLeft + visualViewport.width + 1, body: body.height, results: results?.height, height: visualViewport.height }
  })
  assert.ok(measurements.fits, 'The window must fit without horizontal overflow')
  assert.ok(measurements.body > 30, 'The body must remain usable')
  if (measurements.results !== undefined) assert.ok(measurements.results > (measurements.height < 300 ? 30 : 60), `The toolbar must leave a usable results region: ${JSON.stringify(measurements)}`)
}
try {
  await open()
  await page.screenshot({ path: '/tmp/world-info-layout-small-desktop.png' })
  const topics = dialog().locator('.world-info-topics')
  assert.equal(await topics.isVisible(), true, 'Groups must be visible at the left even with fewer than 50 entries')
  const side = await topics.boundingBox(), catalog = await dialog().locator('.world-info-catalog').boundingBox()
  assert.ok(side.x + side.width <= catalog.x + 1)
  assert.equal(await dialog().locator('.world-info-catalog details').count(), 0, 'Catalog filters and groups must not require accordions')
  await dialog().getByLabel('Entry kind filter', { exact: true }).selectOption('background_lore')
  await dialog().getByLabel('Sort entries', { exact: true }).selectOption('title_asc')
  await topics.getByRole('button', { name: /Coastal history/ }).click()
  await dialog().locator('.world-info-catalog-pages').getByText('1–1 of 1', { exact: true }).waitFor()
  await topics.getByRole('button', { name: 'All groups', exact: true }).click()
  await dialog().locator('.world-info-catalog-pages').getByText('1–2 of 2', { exact: true }).waitFor()
  await button('Organize all matching entries').click()
  await dialog().getByLabel('Bulk action', { exact: true }).selectOption('set_group')
  await dialog().getByLabel('Group name', { exact: true }).fill('Reviewed archive')
  await button('Preview matching entries').click()
  await dialog().getByRole('region', { name: 'Bulk action preview' }).waitFor()
  await button('Confirm matching changes').click(); await button('Confirm').click()
  await topics.getByRole('button', { name: /Reviewed archive/ }).waitFor()
  await button('Organize all matching entries').click()
  await geometry()
  await open(24)
  await page.screenshot({ path: '/tmp/world-info-layout-desktop.png' })
  for (const width of [900, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 844 }); await open(24)
    await geometry()
    await button('Groups & tags').click()
    await topics.getByLabel('Find a group or tag', { exact: true }).waitFor()
    assert.equal(await dialog().locator('.world-info-catalog').isVisible(), false)
    await topics.getByRole('button', { name: /Coastal history/ }).click()
    await button('Back to entries').click()
    await dialog().locator('[data-world-info-entry]').first().waitFor()
    assert.equal(await button('Groups & tags').evaluate(node => document.activeElement === node), true)
    await geometry()
    await button('Groups & tags').click(); await page.keyboard.press('Escape')
    assert.equal(await dialog().isVisible(), true, 'Escape closes the mobile groups panel first')
    assert.equal(await topics.isVisible(), false)
    await button('Groups & tags').click()
    await button('Close World Info').focus(); await page.keyboard.press('Escape')
    assert.equal(await dialog().isVisible(), true, 'Escape closes the groups panel even when focus has moved to the header')
    assert.equal(await topics.isVisible(), false)
    if (width === 390) await page.screenshot({ path: '/tmp/world-info-layout-mobile.png' })
    await dialog().locator('[data-world-info-entry]').first().click()
    await page.getByRole('button', { name: 'Edit entry', exact: true }).waitFor()
    assert.equal(await page.locator('dialog[open]').count(), 1)
    await page.getByRole('button', { name: 'Edit entry', exact: true }).click()
    await page.getByRole('button', { name: 'Cancel editing', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Edit entry', exact: true }).evaluate(node => document.activeElement === node), true, 'Cancel editing must restore focus to the read-view action')
    await page.getByRole('button', { name: 'Edit entry', exact: true }).click()
    await page.getByLabel('Entry title', { exact: true }).fill('An unsaved archive correction')
    await page.getByRole('button', { name: 'Cancel editing', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Edit entry', exact: true }).evaluate(node => document.activeElement === node), true, 'Discarding an edit must restore focus too')
    await page.getByRole('button', { name: 'Back to catalog', exact: true }).click()
    await geometry()
  }
  await page.setViewportSize({ width: 844, height: 390 }); await open(24); await geometry()
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Emulation.setPageScaleFactor', { pageScaleFactor: 2 })
  await page.waitForFunction(() => document.querySelector('.world-info-window').getBoundingClientRect().width <= visualViewport.width)
  await geometry()
  await button('Groups & tags').click(); await button('Back to entries').click()
  assert.deepEqual(errors, [])
  console.log('World Info layout: persistent small-catalog sidebar, visible filters, bulk preview/apply, mobile groups/focus/Escape, separate entry dialog, short landscape and 200% zoom passed.')
} finally { await browser.close() }
