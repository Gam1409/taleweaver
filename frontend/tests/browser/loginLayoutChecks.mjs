import assert from 'node:assert/strict'

export async function checkLoginLayout(page, url) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 720, height: 500 }, { width: 320, height: 568 }]) {
    await page.setViewportSize(viewport)
    await page.goto(url + '?screen=login')
    const root = page.getByRole('region', { name: 'Account access' })
    await root.waitFor()
    const subtitle = root.getByText('Visual Novel', { exact: true })
    assert.ok(await subtitle.evaluate(node => parseFloat(getComputedStyle(node).fontSize)) < await root.getByRole('heading', { name: 'TaleWeaver', exact: true }).evaluate(node => parseFloat(getComputedStyle(node).fontSize)))
    assert.equal(await page.locator('.global-header').count(), 0)
    const size = await root.evaluate(node => ({ height: node.getBoundingClientRect().height, available: node.parentElement.clientHeight, horizontal: node.scrollWidth > node.clientWidth }))
    assert.ok(size.height <= size.available + 1, 'login must fit its scroll container')
    assert.equal(size.horizontal, false)
    const artwork = page.getByAltText('VisualNovel — golden quill and open book', { exact: true })
    await artwork.waitFor()
    await artwork.evaluate(node => node.decode())
    const image = await artwork.evaluate(node => ({ width: node.naturalWidth, height: node.naturalHeight, rendered: node.getBoundingClientRect().width / node.getBoundingClientRect().height }))
    assert.deepEqual([image.width, image.height], [1254, 1254])
    assert.ok(Math.abs(image.rendered - 1) < .001)
    await page.screenshot({ path: `/tmp/taleweaver-login-${viewport.width}.png` })
    const licenses = root.getByRole('button', { name: 'Licenses', exact: true })
    await licenses.scrollIntoViewIfNeeded()
    const box = await licenses.boundingBox()
    assert.ok(box.y >= 0 && box.y + box.height <= viewport.height)
    await licenses.click()
    const licenseDialog = page.getByRole('dialog', { name: 'Licenses', exact: true })
    await licenseDialog.waitFor()
    assert.match(await licenseDialog.innerText(), /Original development: Jean Schmitz · Fork creator: Anton Kuprin/)
    await licenseDialog.getByRole('button', { name: 'Close licenses', exact: true }).click()
    await licenseDialog.waitFor({ state: 'hidden' })
    await root.getByLabel('Username', { exact: true }).fill('Storykeeper')
    const password = root.getByLabel('Password', { exact: true })
    await password.fill('invalid-preview-password')
    await root.getByLabel('Show Password', { exact: true }).check()
    assert.equal(await password.getAttribute('type'), 'text')
    await root.getByLabel('Show Password', { exact: true }).uncheck()
    assert.equal(await password.getAttribute('type'), 'password')
    await root.getByRole('button', { name: 'Begin Journey', exact: true }).click()
    await root.getByText('Invalid credentials. Please try again.', { exact: true }).waitFor()
    await root.getByRole('button', { name: 'Forgot your password?', exact: true }).click()
    await root.getByRole('heading', { name: 'Recover your account', exact: true }).waitFor()
    assert.equal(await root.getByLabel('Username', { exact: true }).inputValue(), 'Storykeeper')
    await root.getByLabel('Recovery code', { exact: true }).fill('invalid-preview-code')
    await root.getByLabel(/^New password/).fill('PreviewPassword1!')
    await root.getByLabel(/^Confirm new password/).fill('DifferentPreviewPassword1!')
    await root.getByText('Passwords do not match.', { exact: true }).waitFor()
    const reset = root.getByRole('button', { name: 'Reset password & sign in', exact: true })
    assert.equal(await reset.isDisabled(), true)
    await root.getByLabel(/^Confirm new password/).fill('PreviewPassword1!')
    await reset.click()
    await root.getByText('Use the fictional recovery code shown above the preview.', { exact: true }).waitFor()
    assert.equal(await root.evaluate(node => node.scrollWidth > node.clientWidth), false)
    await root.getByRole('button', { name: 'Back to sign in', exact: true }).click()
    assert.equal(await root.getByLabel('Username', { exact: true }).inputValue(), 'Storykeeper')
    await password.fill('preview-only')
    await root.getByLabel('Remember Me', { exact: true }).check()
    await root.getByRole('button', { name: 'Begin Journey', exact: true }).click()
    await root.waitFor({ state: 'hidden' })
    await page.locator('.global-header').waitFor()
    assert.equal(await page.evaluate(() => localStorage.getItem('remembered_username')), 'Storykeeper')
    assert.equal(await page.evaluate(() => sessionStorage.getItem('access_token')), 'fictional-preview')
    assert.deepEqual(await page.evaluate(() => window.portalFixture.unhandled), [])
    assert.ok(await page.evaluate(() => window.portalFixture.writes.filter(write => write.path.startsWith('/auth/')).every(write => Object.keys(write.body).join() === 'redacted')))
  }
  await page.goto(url + '?screen=login')
  const root = page.getByRole('region', { name: 'Account access' })
  await root.waitFor()
  assert.equal(await root.getByLabel('Username', { exact: true }).inputValue(), 'Storykeeper')
  assert.equal(await root.getByLabel('Remember Me', { exact: true }).isChecked(), true)
  await root.getByRole('button', { name: 'Forgot your password?', exact: true }).click()
  await root.getByLabel('Recovery code', { exact: true }).fill('DEMO1-DEMO2')
  await root.getByLabel(/^New password/).fill('PreviewPassword1!')
  await root.getByLabel(/^Confirm new password/).fill('PreviewPassword1!')
  await root.getByRole('button', { name: 'Reset password & sign in', exact: true }).click()
  await root.waitFor({ state: 'hidden' })
  await page.locator('.global-header').waitFor()
  assert.deepEqual(errors, [])
}
